-- ----------------------------------------------------------------------
-- 指標の「本社のみ」フラグ（DATA-P0-004 の標準テンプレート出力）
--
-- 役員数・研修時間など一部の指標は本社（連結全体）でのみ収集し、拠点別には
-- 収集しない。従来これをアプリ側で category から推測していたため、
-- 拠点別に収集する human_capital 指標（従業員数）がテンプレートから欠落し、
-- 逆に本社限定の ghg 指標（Scope3 Cat.1）が全拠点へ出力されていた。
-- 判定の唯一の出所をデータモデルへ移す。
--
-- 既存行は false（拠点別に収集する）を既定とする非破壊の列追加。
-- ロールバックは列を無視するだけでよい（docs/known-limitations.md）。
-- RLS は metric_definitions の既存ポリシーがそのまま適用される（0012_rls_core.sql）。
-- ----------------------------------------------------------------------

alter table metric_definitions
  add column hq_only boolean not null default false;

comment on column metric_definitions.hq_only is
  '本社（連結全体）でのみ収集する指標。拠点別の入力テンプレート・割り当てから除外する。';
